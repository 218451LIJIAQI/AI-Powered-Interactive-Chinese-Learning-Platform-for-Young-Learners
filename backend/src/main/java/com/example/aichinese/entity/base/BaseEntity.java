package com.example.aichinese.entity.base;

import java.time.LocalDateTime;
import java.util.Objects;

import org.hibernate.Hibernate;

import jakarta.persistence.Column;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import lombok.Getter;
import lombok.Setter;

/**
 * Common parent of every JPA entity in the platform.
 *
 * <p>Concentrates four cross-cutting responsibilities so each subclass
 * only has to describe its domain-specific columns:</p>
 *
 * <ol>
 *   <li><b>Surrogate primary key.</b> An auto-incremented {@code BIGINT}
 *       generated by MySQL ({@link GenerationType#IDENTITY}). The
 *       {@link #id} field is {@code null} until the row is flushed.</li>
 *   <li><b>Audit timestamps.</b> {@code created_at} and {@code updated_at}
 *       managed by JPA lifecycle callbacks ({@link #onCreate()} and
 *       {@link #onUpdate()}). Spring Data JPA auditing is intentionally
 *       <em>not</em> enabled — keeping the logic local makes the
 *       persistence contract obvious without an extra
 *       {@code @EnableJpaAuditing} configuration class and a
 *       {@code @EntityListeners(AuditingEntityListener.class)} on every
 *       entity.</li>
 *   <li><b>JPA-aware equality.</b> {@link #equals(Object)} and
 *       {@link #hashCode()} are implemented in the canonical Hibernate
 *       way so entities can be safely stored in {@link java.util.Set}
 *       and {@link java.util.Map} structures across persistence
 *       contexts and through lazy-loaded proxies.</li>
 *   <li><b>Diagnostic {@link #toString()}.</b> Returns a compact
 *       {@code "ClassName(id=…)"} representation suitable for log
 *       messages without touching any associations (so it never
 *       triggers a lazy load or {@code LazyInitializationException}).</li>
 * </ol>
 *
 * <h2>Timezone semantics</h2>
 *
 * <p>Both timestamp columns are typed {@link LocalDateTime} and
 * persisted to MySQL {@code datetime(6)}. The JDBC connection in
 * {@code application.yml} is pinned to {@code Asia/Singapore} via
 * {@code serverTimezone} and {@code connectionTimeZone}, so
 * {@link LocalDateTime#now()} (which reads the JVM default zone) and
 * the value the database stores agree on the same wall-clock time as
 * long as the JVM also runs in the Singapore zone. Do not switch to
 * {@link java.time.Instant} or {@link java.time.OffsetDateTime} without
 * first migrating every {@code datetime} column to a timezone-aware
 * type and updating every report that compares these values.</p>
 *
 * <h2>Subclassing rules</h2>
 *
 * <ul>
 *   <li>Subclasses MUST be annotated {@code @Entity} (not
 *       {@code @MappedSuperclass}).</li>
 *   <li>Subclasses MUST NOT override {@link #equals(Object)} or
 *       {@link #hashCode()} — both are declared {@code final} to
 *       enforce this. Lombok's {@code @Data} or
 *       {@code @EqualsAndHashCode} therefore MUST NOT be added; use
 *       {@code @Getter @Setter @NoArgsConstructor} instead, matching
 *       the existing convention across the 57 entities in this
 *       module.</li>
 *   <li>Subclasses MAY override {@link #toString()} when a richer
 *       diagnostic output is genuinely useful, but the override MUST
 *       NOT touch lazy associations.</li>
 * </ul>
 */
@Getter
@Setter
@MappedSuperclass
public abstract class BaseEntity {

    /**
     * Auto-incremented surrogate primary key. {@code null} for transient
     * (not-yet-persisted) instances; assigned by the database on insert.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    /**
     * Wall-clock instant the row was first inserted. Assigned by
     * {@link #onCreate()} when {@code null}; tests and import jobs may
     * pre-populate this field to override the default — the lifecycle
     * callback intentionally respects a non-null value so deterministic
     * fixtures and bulk-import workflows keep working.
     */
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    /**
     * Wall-clock instant the row was last modified. Assigned by
     * {@link #onCreate()} on insert and refreshed by {@link #onUpdate()}
     * before every subsequent {@code UPDATE}. Always greater than or
     * equal to {@link #createdAt}.
     */
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    /**
     * Lifecycle hook fired exactly once before the row is inserted.
     *
     * <p>Sets both timestamps to the current wall-clock time, but only
     * when they have not been pre-populated by the caller. This lets
     * data-import jobs and integration tests provide deterministic
     * timestamps while preserving the default behaviour for normal
     * application code (where neither field is touched before
     * {@code persist}).</p>
     */
    @PrePersist
    protected void onCreate() {
        LocalDateTime now = LocalDateTime.now();
        if (createdAt == null) {
            createdAt = now;
        }
        if (updatedAt == null) {
            updatedAt = now;
        }
    }

    /**
     * Lifecycle hook fired before every {@code UPDATE} statement.
     *
     * <p>Always refreshes {@link #updatedAt}; {@link #createdAt} is
     * pinned by {@code updatable = false} on the column annotation, so
     * even an explicit setter call would be ignored at flush time and
     * the original creation timestamp is preserved.</p>
     */
    @PreUpdate
    protected void onUpdate() {
        updatedAt = LocalDateTime.now();
    }

    /**
     * JPA-aware equality.
     *
     * <p>Two entities are considered equal if and only if:</p>
     * <ul>
     *   <li>They are the same JVM instance, OR</li>
     *   <li>They share the same effective Hibernate class
     *       ({@link Hibernate#getClass(Object)} unwraps lazy proxies so
     *       a proxy compares equal to the entity it stands in for) AND
     *       both have a non-null {@link #id} that is
     *       {@link Objects#equals(Object, Object) equal}.</li>
     * </ul>
     *
     * <p>Two transient (id = {@code null}) instances are
     * <em>not</em> equal even when their non-id fields match. This
     * keeps a {@link java.util.HashSet} stable when entities are added
     * before being persisted and then have their ids assigned — the
     * classic "entity disappears from a Set after the database assigns
     * its id" bug is avoided because {@link #hashCode()} does not
     * depend on the id at all.</p>
     */
    @Override
    public final boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        if (other == null) {
            return false;
        }
        Class<?> thisEffectiveClass = Hibernate.getClass(this);
        Class<?> otherEffectiveClass = Hibernate.getClass(other);
        if (!thisEffectiveClass.equals(otherEffectiveClass)) {
            return false;
        }
        BaseEntity that = (BaseEntity) other;
        return id != null && Objects.equals(id, that.id);
    }

    /**
     * Stable hash code derived from the effective Hibernate class
     * rather than the entity id.
     *
     * <p>This intentional choice keeps the hash code stable across the
     * {@code transient → managed} transition: an entity inserted into
     * a {@link java.util.HashSet} before {@code EntityManager#persist}
     * keeps the same bucket after the database assigns its id, so
     * {@code contains()} continues to find it. An id-based hash code
     * would change at flush time and produce the well-known
     * "ghost element" bug.</p>
     *
     * <p>The trade-off is that every instance of the same entity type
     * collides in the same bucket, so very large
     * {@link java.util.HashMap}s of homogeneous entities degrade to
     * O(n) lookups. In practice the bucket sizes seen by this code
     * base are small and the correctness guarantee is worth more than
     * the micro-optimisation.</p>
     */
    @Override
    public final int hashCode() {
        return Hibernate.getClass(this).hashCode();
    }

    /**
     * Compact diagnostic representation: {@code "ClassName(id=42)"} or
     * {@code "ClassName(id=null)"} for transient instances.
     *
     * <p>Uses {@link Hibernate#getClass(Object)} so a lazy proxy logs
     * as the underlying entity class rather than the
     * {@code ...$HibernateProxy$…} synthetic name. Does not touch any
     * associations, so it is safe to invoke on detached entities and
     * inside log statements that may run after the persistence context
     * has closed.</p>
     */
    @Override
    public String toString() {
        return Hibernate.getClass(this).getSimpleName() + "(id=" + id + ")";
    }
}
