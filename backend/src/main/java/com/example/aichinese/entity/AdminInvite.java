package com.example.aichinese.entity;

import java.time.LocalDateTime;

import com.example.aichinese.entity.base.BaseEntity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Index;
import jakarta.persistence.Table;
import jakarta.persistence.UniqueConstraint;
import lombok.Getter;
import lombok.Setter;

/**
 * An invitation to become an admin. No account exists until the invitee opens the link and sets a password; the new
 * admin account is created, active, at that moment.
 */
@Getter
@Setter
@Entity
@Table(name = "admin_invites", indexes = {
        @Index(name = "idx_admin_invites_email", columnList = "email"),
        @Index(name = "idx_admin_invites_pending", columnList = "accepted_at,cancelled_at,expires_at")
}, uniqueConstraints = {
        @UniqueConstraint(name = "uk_admin_invites_token_hash", columnNames = "token_hash"),
        @UniqueConstraint(name = "uk_admin_invites_unaccepted_email", columnNames = "unaccepted_email")
})
public class AdminInvite extends BaseEntity {

    @Column(name = "email", nullable = false, updatable = false, length = 150)
    private String email;

    /**
     * At most one unaccepted invite per email address, enforced by the database without SERIALIZABLE range locks.
     * Generated by MySQL so accepted invites retain history while freeing the email for future re-invites if ever needed.
     */
    @Column(name = "unaccepted_email", insertable = false, updatable = false,
            columnDefinition = "varchar(150) generated always as (case when accepted_at is null then email else null end) stored")
    private String unacceptedEmail;

    /** Replaced when the invite is sent again, so only the newest link works. */
    @Column(name = "token_hash", nullable = false, length = 64)
    private String tokenHash;

    @Column(name = "expires_at", nullable = false)
    private LocalDateTime expiresAt;

    @Column(name = "accepted_at")
    private LocalDateTime acceptedAt;

    /**
     * Set by "Cancel invite": the link stops working. The invite is kept so that Undo can bring the same link back;
     * Undo and sending the invite again clear it.
     */
    @Column(name = "cancelled_at")
    private LocalDateTime cancelledAt;
}
