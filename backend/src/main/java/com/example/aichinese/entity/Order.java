package com.example.aichinese.entity;

import java.math.BigDecimal;

import com.example.aichinese.entity.base.BaseEntity;
import com.example.aichinese.entity.enums.PaymentStatus;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.Index;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import jakarta.persistence.Version;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;

/**
 * Top-level commercial order header placed by a {@link StudentProfile}.
 *
 * <p>An order aggregates one or more {@link OrderItem}s and is
 * accompanied by zero or more {@link PaymentRecord}s tracking provider
 * attempts. The {@link #paymentStatus} mirrors the state of the most
 * recent successful payment record and follows the
 * {@link com.example.aichinese.entity.enums.PaymentStatus} state
 * machine.</p>
 *
 * <p>{@link #orderNumber} is a globally-unique human-friendly
 * identifier (e.g. {@code "ORD-20260524-AB12"}) generated by
 * {@code CheckoutService} so customer-facing emails and refund disputes
 * never expose the auto-increment {@code id}.</p>
 *
 * <p>{@link #version} (JPA {@link jakarta.persistence.Version}) provides
 * optimistic locking against the inevitable race between Stripe webhook
 * delivery and student-initiated cancellation; the second writer
 * receives an {@link org.hibernate.StaleObjectStateException} and the
 * service layer retries.</p>
 *
 * <p>{@link #checkoutSource} is a free-form short tag (e.g.
 * {@code "web"}, {@code "mobile_v1"}) used by analytics to slice
 * conversion funnels.</p>
 */
@Getter
@Setter
@NoArgsConstructor
@Entity
@Table(name = "orders", indexes = {
        @Index(name = "idx_orders_student_id", columnList = "student_id"),
        @Index(name = "idx_orders_payment_status", columnList = "payment_status")
})
public class Order extends BaseEntity {

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "student_id", nullable = false)
    private StudentProfile student;

    @Column(name = "order_number", nullable = false, unique = true, length = 50)
    private String orderNumber;

    @Column(name = "total_amount", nullable = false, precision = 10, scale = 2)
    private BigDecimal totalAmount;

    @Version
    @Column(name = "version", nullable = false)
    private Long version = 0L;

    @Column(name = "currency_code", nullable = false, length = 3)
    private String currencyCode = "MYR";

    @Enumerated(EnumType.STRING)
    @Column(name = "payment_status", nullable = false, length = 30)
    private PaymentStatus paymentStatus = PaymentStatus.PENDING;

    @Column(name = "checkout_source", length = 30)
    private String checkoutSource;
}
